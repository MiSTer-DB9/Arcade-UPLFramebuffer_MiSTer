// DB9MD: Attack=B, Jump=C, Coin=MODE, Start 1P=START, Start 2P=X, Pause=Y
wire  [35:0] db9_remap_default_db15  = 36'hFFF87AB54;
wire  [35:0] db9_remap_default_db9md = 36'hFFF87AB65;
