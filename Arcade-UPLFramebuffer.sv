////////////////////   CLOCKS   ///////////////////
//   Fabric 60.000 MHz = 50 MHz refclk x 12/10 (integer PLL: M=12, N=1, C=10).
//     60 / 10 = 6.0 MHz = XTAL 12 / 2 -> main Z80 + pixel clock
//     60 / 12 = 5.0 MHz = 5 MHz XTAL  -> sound Z80
//     60 / 40 = 1.5 MHz = XTAL 12 / 8 -> both YM2203
